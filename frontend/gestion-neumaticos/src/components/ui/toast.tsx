import * as React from "react"
import { Toast as ToastPrimitive } from "@base-ui/react/toast"
import type { ParseKeys, TFunction } from "i18next"
import {
  CircleCheckIcon,
  InfoIcon,
  Loader2Icon,
  OctagonXIcon,
  TriangleAlertIcon,
  XIcon,
} from "lucide-react"
import { useTranslation } from "react-i18next"

import { Button } from "@/components/ui/button"
import { NAMESPACES } from "@/lib/i18n/config"
import { cn } from "@/lib/utils"

/**
 * Clave de traducción de cualquier namespace configurado. Las de `common` van
 * sueltas (`"toast.close"`); las del resto, prefijadas (`"auth:login.title"`).
 */
export type ToastKey = ParseKeys<typeof NAMESPACES>

/**
 * Payload que el helper `notify` deja en `toast.data`. Se guardan las claves de
 * traducción y no el texto ya resuelto: `ToastList` las resuelve en cada render,
 * así un toast visible se retraduce al cambiar de idioma en lugar de quedar
 * congelado en el idioma con el que se disparó.
 */
export type ToastData = {
  titleKey?: ToastKey
  descriptionKey?: ToastKey
  actionLabelKey?: ToastKey
  values?: Record<string, unknown>
}

/** Devuelve `undefined` si no hay clave, para que el primitivo use su valor por defecto. */
function resolveKey(
  t: TFunction<typeof NAMESPACES>,
  key: ToastKey | undefined,
  values: Record<string, unknown> | undefined
) {
  // `values ?? {}` no es cosmético: con `undefined`, TS elige la sobrecarga de
  // `t(key, defaultValue)` en vez de la de opciones de interpolación.
  return key === undefined ? undefined : t(key, values ?? {})
}

const toast = ToastPrimitive.createToastManager()

function ToastProvider({ ...props }: ToastPrimitive.Provider.Props) {
  return <ToastPrimitive.Provider {...props} />
}

function ToastPortal({ ...props }: ToastPrimitive.Portal.Props) {
  return <ToastPrimitive.Portal data-slot="toast-portal" {...props} />
}

function ToastViewport({ className, ...props }: ToastPrimitive.Viewport.Props) {
  return (
    <ToastPrimitive.Viewport
      data-slot="toast-viewport"
      className={cn(
        "pointer-events-none fixed inset-x-4 bottom-4 z-50 mx-auto w-auto max-w-sm outline-none sm:right-4 sm:left-auto sm:mx-0 sm:w-full",
        className
      )}
      {...props}
    />
  )
}

